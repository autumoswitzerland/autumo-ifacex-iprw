# VARS
# Override via environment: IPRW_VERSION=3.0.1 ./make.sh create
IPRW_VERSION=${IPRW_VERSION:-3.0.0}
# ifaceX lib manifest (generated and checked in by the ifaceX build)
IFACEX_LIBS_MANIFEST=${IFACEX_LIBS_MANIFEST:-/Users/Mike/Development/git/repository/autumo-ifacex/ifacex-libs.txt}




# ------------------------------------------------
# -------- Usage
# ------------------------------------------------
if [ "$1" = "help" -o "$#" -lt 1 ]
then
	echo " "
	echo "make clear"
	echo "make create"
	echo " "
	echo " "
	exit 1
fi


mkdir -p product


# ------------------------------------------------
# -------- DELETE PRODUCT
# ------------------------------------------------
if [ "$1" = "clear" ]
then
	cd product

	# remove working directory
	if [ -d "autumo-ifaceX-iprw-$IPRW_VERSION" ]
	then
		rm -Rf autumo-ifaceX-iprw-$IPRW_VERSION
	fi
	
	# remove package
	if [ -f "autumo-ifaceX-iprw-$IPRW_VERSION.zip" ]
	then
    	rm autumo-ifaceX-iprw-*.zip
	fi
	
	cd ..
	
	exit 1
fi



# ------------------------------------------------
# -------- CREATE PRODUCT
# ------------------------------------------------
if [ "$1" = "create" -a "$#" -gt 0 ]
then



# -----------------------------
# ---- Cleanup & Prepare
# -----------------------------

	echo "-> Cleanup & prepare..."
	
	# delete old product package
	if [ -d "product/autumo-ifaceX-iprw-$IPRW_VERSION" ]
	then
		rm -Rf product/autumo-ifaceX-iprw-$IPRW_VERSION
	fi	

	# go to product
	cd product
	
	# make working directory
	mkdir autumo-ifaceX-iprw-$IPRW_VERSION



# -----------------------------
# ---- Go to ifaceX package
# -----------------------------

	# go to ifaceX package folder
	cd autumo-ifaceX-iprw-$IPRW_VERSION



# -----------------------------
# ---- Copying
# -----------------------------
		

	echo "-> Copying..."
	
	mkdir -p lib


	##  Sorting out libs beforehand, example:
	#LIST=(`ls ../../mod-google-storage/lib/*.jar`)
	#LIST=${LIST[@]/*failureaccess*}
	#LIST=${LIST[@]/*google-oauth-client*}
	#LIST=${LIST[@]/*j2objc-annotations*}
	#LIST=${LIST[@]/*jsr305*}
	#LIST=${LIST[@]/*listenablefuture*}
	#cp $LIST lib/


	# COPY LIBS
	

	# Base libs
	cp ../../lib/*.jar lib/
	
	# Module 'mod-az-aws-s3'
	cp ../../mod-az-aws-s3/lib/*.jar lib/
	
	
	# Module 'mod-bb-b2'
	cp ../../mod-bb-b2/lib/*.jar lib/

	
	# Module 'mod-dbox'
	cp ../../mod-dbox/lib/*.jar lib/

	
	# Module 'mod-ftp'
	cp ../../mod-ftp/lib/*.jar lib/

	
	# Module 'mod-google-drive'
	cp ../../mod-google-drive/lib/*.jar lib/
	
	
	# Module 'mod-google-storage'
	cp ../../mod-google-storage/lib/*.jar lib/
	
	
	# Module 'mod-ms-azure'
	cp ../../mod-ms-azure/lib/*.jar lib/
	
	
	# Module 'mod-ms-graph'
	cp ../../mod-ms-graph/lib/*.jar lib/

	
	# Module 'mod-nifi'
	cp ../../mod-nifi/lib/*.jar lib/

	
	# Module 'mod-os'
	cp ../../mod-os/lib/*.jar lib/

	
	# Module 'mod-sftp'
	cp ../../mod-sftp/lib/*.jar lib/

	
	# Module 'mod-webdav'
	cp ../../mod-webdav/lib/*.jar lib/



	# REMOVE ifaceX Doublettes
	# Manifest is generated by the ifaceX build into the ifaceX project root.
	# Only jars with the exact same file name (= same version) are removed.
	if [ ! -f "$IFACEX_LIBS_MANIFEST" ]
	then
		echo "ERROR: ifaceX lib manifest missing: $IFACEX_LIBS_MANIFEST" >&2
		exit 1
	fi

	while IFS= read -r jar
	do
		[ -n "$jar" ] && rm -f "lib/$jar"
	done < "$IFACEX_LIBS_MANIFEST"

	# WARN if a packaged jar has the same artifact but another version than ifaceX
	for j in lib/*.jar
	do
		[ -e "$j" ] || continue
		b=$(basename "$j")
		stem=$(printf '%s\n' "$b" | sed 's/-[0-9][0-9A-Za-z._-]*\.jar$//')
		[ "$stem" = "$b" ] && continue
		while IFS= read -r ref
		do
			case "$ref" in
				"$stem"-*.jar)
					[ "$ref" != "$b" ] && echo "WARN: version drift: lib/$b vs ifaceX $ref" >&2
					;;
			esac
		done < "$IFACEX_LIBS_MANIFEST"
	done



	# COPY Templates
	
	mkdir -p interfaces/examples
	cp ../../interfaces/*.template interfaces/
	cp ../../interfaces/examples/*.* interfaces/examples/

	
	
	# COPY LICENSE
	cp ../../LICENSE.md .
	# COPY README
	cp ../../README.md .

	

# -----------------------------
# ---- Create Product
# -----------------------------

	echo "-> Create PRODUCT..."

	# LEAVE PACKAGE FOLDER
	cd ..

	# create archive (remove old one first, 'zip -r' would keep stale entries)
	rm -f "autumo-ifaceX-iprw-${IPRW_VERSION}.zip"
	zip -r "autumo-ifaceX-iprw-${IPRW_VERSION}.zip" autumo-ifaceX-iprw-${IPRW_VERSION} \
		-x "*/.DS_Store" \
		-x "*/__MACOSX"

	# delete build directory
	rm -Rf autumo-ifaceX-iprw-${IPRW_VERSION}
	

	
# -----------------------------
# ---- END
# -----------------------------
	
	# leave product folder
	cd ..

	
else
	echo "Nope! -> make create"
	echo " "
fi



